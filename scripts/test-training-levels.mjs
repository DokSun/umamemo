import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
const Levels=runInNewContext(readFileSync('training-levels.js','utf8')+'\nTrainingLevels');
const create=()=>({turns:{junior:Array(24).fill(null),classic:Array(24).fill(null),senior:Array(24).fill(null)}});
const level=(s,through,type='speed')=>Levels.calculate(s,through).levels.find(x=>x.type===type);
const s=create();
assert.equal(level(s,0).level,1);
for(let i=0;i<4;i++)s.turns.junior[i]='speed';
assert.equal(level(s,3).level,1);
assert.equal(level(s,4).level,2);
assert.equal(level(s,4).count,4);
assert.equal(level(s,4).untilNext,4);
assert.equal(level(s,24).level,3,'Classic new year increases all training levels');
assert.equal(level(s,48).level,4,'Senior new year increases all training levels');
assert.equal(level(s,24,'wisdom').level,2);
assert.equal(level(s,48,'wisdom').level,3);
assert.equal(Levels.calculate(s,36).summerCamp,true,'Classic July early is summer camp');
assert.equal(Levels.calculate(s,40).summerCamp,false,'Classic September is regular training');
assert.equal(Levels.calculate(s,60).summerCamp,true,'Senior July is summer camp');
assert.equal(Levels.calculate(s,64).summerCamp,false,'Senior September is regular training');
for(let i=12;i<16;i++)s.turns.classic[i]='speed';
assert.equal(level(s,40).count,4,'Classic summer training is excluded');
for(let i=12;i<16;i++)s.turns.senior[i]='speed';
assert.equal(level(s,64).count,4,'Senior summer training is excluded');
for(let i=0;i<4;i++)s.turns.classic[i]='speed';
assert.equal(level(s,28).level,4,'A further four real trainings increase level');
assert.equal(level(s,48).level,5,'Level capped at 5');
assert.equal(Levels.calculate(s,36).levels.every(x=>x.level===5),true,'Every type level is 5 during summer');
assert.equal(level(s,40,'wisdom').level,2,'Summer level 5 is temporary');
assert.equal(level(s,0).level,1,'Out-of-window actions must not count');
assert.equal(Levels.calculate(s,100).completed,72);
console.log('PASS: training-level increments, year boundaries, camp and cap');